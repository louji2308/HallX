"""Typed errors for the corpus registry and ACL service."""

from __future__ import annotations

from enum import Enum


class CorpusErrorCode(str, Enum):
    CORPUS_NOT_FOUND = "CORPUS_NOT_FOUND"
    CORPUS_ACL_DENIED = "CORPUS_ACL_DENIED"
    CORPUS_ROLE_REQUIRED = "CORPUS_ROLE_REQUIRED"
    DUPLICATE_RESOURCE = "DUPLICATE_RESOURCE"
    VERSION_IMMUTABLE = "VERSION_IMMUTABLE"
    VERSION_TRANSITION_INVALID = "VERSION_TRANSITION_INVALID"
    SUPERSESSION_INVALID = "SUPERSESSION_INVALID"
    EFFECTIVE_WINDOW_INVALID = "EFFECTIVE_WINDOW_INVALID"
    CHUNK_HASH_MISMATCH = "CHUNK_HASH_MISMATCH"
    CANONICALIZATION_MISMATCH = "CANONICALIZATION_MISMATCH"
    SNAPSHOT_NOT_FOUND = "SNAPSHOT_NOT_FOUND"
    SNAPSHOT_IMMUTABLE = "SNAPSHOT_IMMUTABLE"
    SNAPSHOT_HASH_MISMATCH = "SNAPSHOT_HASH_MISMATCH"
    SNAPSHOT_INCOMPLETE = "SNAPSHOT_INCOMPLETE"
    SPLIT_FAMILY_LEAKAGE = "SPLIT_FAMILY_LEAKAGE"
    SPLIT_DUPLICATE_SOURCE = "SPLIT_DUPLICATE_SOURCE"
    SPLIT_LOCKED = "SPLIT_LOCKED"
    SPLIT_INVALID = "SPLIT_INVALID"
    PRECEDENCE_INVALID = "PRECEDENCE_INVALID"
    CONFLICT_INVALID = "CONFLICT_INVALID"
    SCHEMA_VERSION_UNSUPPORTED = "SCHEMA_VERSION_UNSUPPORTED"
    MIGRATION_FAILED = "MIGRATION_FAILED"
    CORPUS_INTEGRITY_ERROR = "CORPUS_INTEGRITY_ERROR"


class CorpusError(Exception):
    """A fail-closed corpus error with a bounded, non-content message."""

    def __init__(self, code: CorpusErrorCode, message: str) -> None:
        super().__init__(f"{code.value}: {message}")
        self.code = code
        self.message = message
